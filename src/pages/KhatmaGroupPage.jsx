// ─── helpers ─────────────────────────────────────────────────────────────────
// Room codes are generated by the server (docs/API.md). Only the pending-join
// code is kept on the device (sessionStorage) so it survives the login redirect.
const PENDING_JOIN_KEY = 'nq_pending_join';
function getPendingJoin() { try { return sessionStorage.getItem(PENDING_JOIN_KEY) || ''; } catch { return ''; } }
function setPendingJoin(c) { try { c ? sessionStorage.setItem(PENDING_JOIN_KEY, c) : sessionStorage.removeItem(PENDING_JOIN_KEY); } catch {} }
function shareUrl(code) { return `${window.location.origin}/khatma-group?join=${code}`; }
// Rooms used to be cached on the device — drop that old copy once.
try { localStorage.removeItem('nq_gkhatmat'); } catch {}

const POLL_MS = 10_000;

function roomProgress(room) {
  const parts = room.parts || [];
  const total = room.total ?? (parts.length || (room.mode === 'juz' ? 30 : 60));
  const done  = room.done_count ?? parts.filter(p => p.done).length;
  return { done, total, pct: total > 0 ? Math.round((done / total) * 100) : 0 };
}

