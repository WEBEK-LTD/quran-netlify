// ─── Create Room ──────────────────────────────────────────────────────────────
function CreateRoom({ user, onBack, onCreated }) {
  const [step,      setStep]    = useState(1);
  const [name,      setName]    = useState('');
  const [mode,      setMode]    = useState('juz');
  const [isPublic,  setPublic]  = useState(false);
  const [members,   setMembers] = useState(['أنا']);
  const [newMember, setNew]     = useState('');
  const [assign,    setAssign]  = useState({});
  const [nameErr,   setNameErr] = useState('');
  const [creating,  setCreating] = useState(false);
  const [createErr, setCreateErr] = useState('');

  const parts = mode === 'juz'
    ? JUZ_DATA.map(j => ({ id: j.juz, label: `الجزء ${toArabicNum(j.juz)}` }))
    : Array.from({length:60}, (_,i) => ({ id: i+1, label: `الحزب ${toArabicNum(i+1)}` }));

  function addMember() {
    const m = newMember.trim();
    if (m && !members.includes(m)) setMembers(p=>[...p,m]);
    setNew('');
  }
  function autoDistribute() {
    const a = {};
    parts.forEach((p,i) => { a[p.id] = members[i % members.length]; });
    setAssign(a);
  }
  async function create() {
    if (!name.trim()) { setNameErr('أدخل اسم المتوفى'); setStep(1); return; }
    setCreating(true); setCreateErr('');
    const err = await onCreated({
      deceased_name: name.trim(),
      mode,
      is_public: isPublic,
      parts: parts.map(p => ({ part_index: p.id, label: p.label, assignee: assign[p.id] || '' })),
    });
    // on success the parent switches to the room view (this component unmounts)
    if (err) { setCreateErr(err); setCreating(false); }
  }

  return (
    <div className={styles.page}>
      <div className={styles.topBar}>
        <button className={styles.backBtn} onClick={onBack}>← رجوع</button>
        <h1>خاتمة جديدة</h1>
        <div style={{width:60}}/>
      </div>

      <div className={styles.stepInd}>
        {[1,2].map(n => (
          <div key={n} className={`${styles.stepDot} ${step>=n ? styles.stepActive : ''}`}>
            {toArabicNum(n)}
          </div>
        ))}
      </div>

      {step === 1 && (
        <div className={styles.form}>
          <label className={styles.lbl}>اسم المتوفى / المتوفاة</label>
          <input className={styles.inp} placeholder="مثال: الحاج محمد أحمد"
            value={name} onChange={e=>{ setName(e.target.value); setNameErr(''); }} dir="rtl"
            onKeyDown={e=>e.key==='Enter' && name.trim() && setStep(2)} autoFocus />
          {nameErr && <p className={styles.joinErr} role="alert">{nameErr}</p>}

          <label className={styles.lbl}>نوع التقسيم</label>
          <div className={styles.modeRow}>
            {[['juz','30 جزء'],['hizb','60 حزب']].map(([v,l]) => (
              <button key={v} className={`${styles.modeBtn} ${mode===v?styles.modeBtnA:''}`}
                onClick={()=>setMode(v)}>{l}</button>
            ))}
          </div>

          <label className={styles.lbl}>الخصوصية</label>
          <div className={styles.modeRow}>
            <button className={`${styles.modeBtn} ${!isPublic?styles.modeBtnA:''}`}
              onClick={()=>setPublic(false)}>🔒 خاص — بالكود فقط</button>
            <button className={`${styles.modeBtn} ${isPublic?styles.modeBtnA:''}`}
              onClick={()=>setPublic(true)}>🌐 عام — يظهر للجميع</button>
          </div>

          <label className={styles.lbl}>الأعضاء</label>
          <div className={styles.chips}>
            {members.map((m,i) => (
              <div key={i} className={styles.chip}>
                <span>{m}</span>
                {members.length > 1 &&
                  <button onClick={()=>setMembers(p=>p.filter((_,j)=>j!==i))}>✕</button>}
              </div>
            ))}
          </div>
          <div className={styles.addRow}>
            <input className={styles.inp} placeholder="اسم عضو جديد..."
              value={newMember} onChange={e=>setNew(e.target.value)}
              onKeyDown={e=>e.key==='Enter' && addMember()} dir="rtl" />
            <button className={styles.addBtn} onClick={addMember}>＋</button>
          </div>

          <button className={styles.nextBtn}
            onClick={()=>name.trim() ? setStep(2) : setNameErr('أدخل اسم المتوفى')}>
            التالي ←
          </button>
        </div>
      )}

      {step === 2 && (
        <div className={styles.form}>
          <div className={styles.assignHead}>
            <h3>توزيع {mode==='juz'?'الأجزاء':'الأحزاب'}</h3>
            <div style={{display:'flex',gap:6}}>
              <button className={styles.autoBtn} onClick={autoDistribute}>⚡ تلقائي</button>
              <button className={styles.clearBtn} onClick={()=>setAssign({})}>مسح</button>
            </div>
          </div>
          <div className={styles.partGrid}>
            {parts.map(p => (
              <div key={p.id} className={`${styles.partCard} ${assign[p.id]?styles.partA:''}`}>
                <div className={styles.partLbl}>{p.label}</div>
                <select className={styles.partSel}
                  value={assign[p.id]||''}
                  onChange={e=>setAssign(a=>({...a,[p.id]:e.target.value}))}>
                  <option value="">— غير محدد —</option>
                  {members.map(m=><option key={m} value={m}>{m}</option>)}
                </select>
              </div>
            ))}
          </div>
          <div className={styles.createBtns}>
            <button className={styles.backStepBtn} onClick={()=>setStep(1)}>← السابق</button>
            <button className={styles.nextBtn} style={{flex:1}} onClick={create} disabled={creating}>
              {creating ? 'جارٍ الإنشاء...' : 'إنشاء الخاتمة ✓'}
            </button>
          </div>
          {createErr && <p className={styles.joinErr} role="alert">⚠️ {createErr}</p>}
        </div>
      )}
    </div>
  );
}

// ─── Room View ────────────────────────────────────────────────────────────────
function RoomView({ room, user, onBack, onUpdate, onGone, showToast }) {
  const [myName,       setMyName]  = useState(() => {
    try { return localStorage.getItem('nq_khatma_name') || displayNameOf(user); } catch { return displayNameOf(user); }
  });
  const [nameInput,    setNameInp] = useState('');
  const [filterMem,    setFilter]  = useState('all');
  const [confirm,      setConfirm] = useState(null);   // 'round' | 'delete' | 'leave'
  const [busy,         setBusy]    = useState(false);
  const [copied,       setCopied]  = useState('');
  const [claiming,     setClaiming]= useState(null);   // part_index being changed
  const [syncErr,      setSyncErr] = useState(false);
  const aliveRef  = useRef(true);
  const copyTimer = useRef(null);
  const roomRef   = useRef(room);
  roomRef.current = room;

  const parts      = room.parts || [];
  const isOwner    = !!room.is_owner;
  const done       = parts.filter(p => p.done).length;
  const total      = parts.length;
  const pct        = total > 0 ? Math.round((done / total) * 100) : 0;
  const isComplete = done === total && total > 0;

  // كل الأسماء اللي اختارت (من الـ takers + assignees)
  const allNames = [...new Set([
    ...parts.flatMap(p => (p.takers || []).map(tk => tk.name)),
    ...parts.map(p => p.assignee),
  ].filter(Boolean))];

  // ─── Poll the open room every 10 s (other members' progress) ─────────────
  useEffect(() => {
    aliveRef.current = true;
    async function tick() {
      if (document.hidden) return;
      try {
        const fresh = await getGroupKhatmaByCode(roomRef.current.code);
        if (!aliveRef.current) return;
        onUpdate(fresh); setSyncErr(false);
      } catch (e) {
        if (!aliveRef.current) return;
        if (e?.code === 'not_found') { onGone('⚠️ حُذفت هذه الخاتمة'); return; }
        setSyncErr(true);
      }
    }
    const t = setInterval(tick, POLL_MS);
    return () => { aliveRef.current = false; clearInterval(t); clearTimeout(copyTimer.current); };
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [room.code]);

  // Run an action that returns the updated Room
  async function act(pi, fn, okMsg) {
    setClaiming(pi);
    try {
      const updated = await fn();
      if (!aliveRef.current) return;
      if (updated && updated.parts) onUpdate(updated);
      if (okMsg) showToast(okMsg);
    } catch (e) {
      if (aliveRef.current) showToast('⚠️ ' + errorMessage(e, 'خطأ — حاول مرة تانية'));
    }
    if (aliveRef.current) setClaiming(null);
  }

  // ─── Save name ─────────────────────────────────────────────────────────────
  function saveName() {
    const n = nameInput.trim();
    if (!n) return;
    setMyName(n);
    try { localStorage.setItem('nq_khatma_name', n); } catch {}
    setNameInp('');
    showToast('✅ تم حفظ اسمك: ' + n);
  }

  // ─── Claim a part / toggle my "done" ──────────────────────────────────────
  function handleClaim(part) {
    const pi = part.part_index;
    const mine = (part.takers || []).find(tk => tk.is_me);
    if (mine) {
      act(pi, () => setPartDone(room.code, pi, !mine.done), '✓ تم تحديث حالة الجزء');
      return;
    }
    if (!myName) { showToast('أدخل اسمك أولاً'); return; }
    act(pi, () => claimPart(room.code, pi, myName), '✅ أخذت ' + part.label);
  }

  function handleRelease(part) {
    act(part.part_index, () => releasePart(room.code, part.part_index), 'تم ترك ' + part.label);
  }

  // ─── Checkbox: only a taker of the part, or the owner ─────────────────────
  function togglePart(part) {
    const iTook = (part.takers || []).some(tk => tk.is_me);
    if (!iTook && !isOwner) { showToast('خذ الجزء أولاً بزر «أنا هاخده»'); return; }
    act(part.part_index, () => setPartDone(room.code, part.part_index, !part.done));
  }

  // ─── Owner / member actions (confirmed in-app) ────────────────────────────
  async function runConfirmed() {
    const what = confirm;
    setBusy(true);
    try {
      if (what === 'round') {
        const updated = await startNewRound(room.code);
        if (!aliveRef.current) return;
        if (updated) onUpdate(updated);
        showToast('✨ بدأت ختمة جديدة!');
      } else if (what === 'delete') {
        await deleteGroupKhatma(room.code);
        if (!aliveRef.current) return;
        onGone('🗑️ تم حذف الخاتمة');
        return;
      } else if (what === 'leave') {
        await leaveGroupKhatma(room.code);
        if (!aliveRef.current) return;
        onGone('تم الخروج من الخاتمة');
        return;
      }
    } catch (e) {
      if (aliveRef.current) showToast('⚠️ ' + errorMessage(e, 'تعذّر تنفيذ الإجراء'));
    }
    if (aliveRef.current) { setBusy(false); setConfirm(null); }
  }

  async function toggleVisibility() {
    if (!isOwner) return;
    const next = !room.is_public;
    try {
      const updated = await updateKhatmaVisibility(room.code, next);
      if (!aliveRef.current) return;
      onUpdate({ ...room, ...(updated || {}), is_public: updated?.is_public ?? next, parts: updated?.parts || room.parts });
      showToast(next ? '🌐 أصبحت الخاتمة عامة' : '🔒 أصبحت الخاتمة خاصة');
    } catch (e) {
      if (aliveRef.current) showToast('⚠️ ' + errorMessage(e, 'تعذّر تغيير الخصوصية'));
    }
  }

  function flashCopied(kind) {
    setCopied(kind);
    clearTimeout(copyTimer.current);
    copyTimer.current = setTimeout(() => setCopied(''), 2000);
  }
  function copyCode() {
    navigator.clipboard?.writeText(room.code)?.catch?.(() => {});
    flashCopied('code');
    showToast('تم نسخ الكود: ' + room.code);
  }
  function copyLink() {
    navigator.clipboard?.writeText(shareUrl(room.code))?.catch?.(() => {});
    flashCopied('link');
    showToast('✓ تم نسخ الرابط');
  }

  const visible = filterMem === 'all'
    ? parts
    : parts.filter(p => {
        const names = (p.takers || []).map(tk => tk.name);
        return (p.assignee || p.done_by_name) === filterMem || names.includes(filterMem);
      });

  const CONFIRMS = {
    round:  { title: 'بدء ختمة جديدة؟', body: 'سيُحتفظ بالتوزيع ويبدأ العداد من جديد', ok: 'نعم، ابدأ' },
    delete: { title: 'حذف الخاتمة نهائياً؟', body: 'ستُحذف الخاتمة وكل تقدّم المشاركين فيها. لا يمكن التراجع.', ok: 'نعم، احذف' },
    leave:  { title: 'الخروج من الخاتمة؟', body: 'ستختفي من «ختماتي». يمكنك العودة لاحقاً بالكود.', ok: 'نعم، اخرج' },
  };

  return (
    <div className={styles.page}>
      <div className={styles.topBar}>
        <button className={styles.backBtn} onClick={onBack}>← رجوع</button>
        <h1 className={styles.roomH1}>🕌 {room.deceased_name}</h1>
        <div style={{ width: 60 }} />
      </div>

      {syncErr && (
        <p className={styles.joinErr} style={{ textAlign: 'center' }}>⚠️ تعذّر تحديث الخاتمة — تُعرض آخر نسخة محمّلة</p>
      )}

      {/* Code card */}
      <div className={styles.codeCard}>
        <div className={styles.codeLeft}>
          <span className={styles.codeLbl}>كود الانضمام</span>
          <span className={styles.codeVal}>{room.code}</span>
        </div>
        <div className={styles.codeBtns}>
          <button className={`${styles.codeBtn} ${copied === 'code' ? styles.codeCopied : ''}`} onClick={copyCode}>
            {copied === 'code' ? '✓' : '📋'} كود
          </button>
          <button className={`${styles.codeBtn} ${copied === 'link' ? styles.codeCopied : ''}`} onClick={copyLink}>
            {copied === 'link' ? '✓' : '🔗'} رابط
          </button>
          {isOwner ? (
            <button className={`${styles.codeBtn} ${room.is_public ? styles.publicOn : ''}`} onClick={toggleVisibility}>
              {room.is_public ? '🌐 عام' : '🔒 خاص'}
            </button>
          ) : (
            <span className={room.is_public ? styles.publicTag : styles.privateTag}>
              {room.is_public ? '🌐 عام' : '🔒 خاص'}
            </span>
          )}
        </div>
      </div>

      {/* اسمك */}
      <div className={styles.nameBox}>
        {myName ? (
          <div className={styles.myNameRow}>
            <span className={styles.myNameLbl}>اسمك:</span>
            <span className={styles.myNameVal}>{myName}</span>
            <button className={styles.changeName} onClick={() => { setMyName(''); try { localStorage.removeItem('nq_khatma_name'); } catch {} }}>
              تغيير
            </button>
          </div>
        ) : (
          <div className={styles.nameInputRow}>
            <input
              className={styles.nameInput}
              placeholder="أدخل اسمك لتأخذ جزءاً..."
              value={nameInput}
              onChange={e => setNameInp(e.target.value)}
              onKeyDown={e => e.key === 'Enter' && saveName()}
            />
            <button className={styles.nameBtn} onClick={saveName}>حفظ</button>
          </div>
        )}
      </div>

      {/* Progress */}
      <div className={`${styles.progressBar} ${styles.progress}`}>
        <div className={styles.progressFill} style={{ width: pct + '%' }} />
      </div>
      <div className={styles.progressLbl}>
        <span>{done} من {total} {room.mode === 'juz' ? 'جزء' : 'حزب'}</span>
        <span>{pct}%</span>
      </div>

      {/* Complete banner */}
      {isComplete && (
        <div className={styles.completeBanner}>
          <span>🏆</span>
          <div>
            <strong>اكتملت الخاتمة!</strong>
            {(room.completions || 0) > 0 && <span> — {toArabicNum(room.completions)} ختمة</span>}
          </div>
          {isOwner && <button className={styles.newRoundBtn} onClick={() => setConfirm('round')}>ختمة جديدة</button>}
        </div>
      )}

      {/* Filter */}
      {allNames.length > 1 && (
        <div className={styles.filterRow}>
          {['all', ...allNames].map(m => (
            <button key={m}
              className={`${styles.filterBtn} ${filterMem === m ? styles.filterA : ''}`}
              onClick={() => setFilter(m)}>
              {m === 'all' ? 'الكل' : m}
            </button>
          ))}
        </div>
      )}

      {/* Parts */}
      <div className={styles.partsList}>
        {visible.map(part => {
          const pi = part.part_index;
          const partTakers = part.takers || [];
          const myTaker    = partTakers.find(tk => tk.is_me);
          const iClaimed   = !!myTaker;
          const iDone      = !!myTaker?.done;

          return (
            <div key={pi}
              className={`${styles.partRow} ${part.done ? styles.partDone : ''} ${iClaimed ? styles.partClaimed : ''}`}>

              {/* Done checkbox — للي أخذ الجزء أو منشئ الخاتمة */}
              <div
                className={`${styles.check} ${part.done ? styles.checkDone : ''}`}
                onClick={() => { if (claiming !== pi) togglePart(part); }}>
                {part.done ? '✓' : ''}
              </div>

              <div className={styles.partInfo}>
                <span className={styles.partName}>{part.label}</span>

                {part.assignee && (
                  <span className={`${styles.partMem} ${part.done ? styles.partMemDone : ''}`}>
                    {part.assignee}
                  </span>
                )}

                {partTakers.length > 0 && (
                  <div className={styles.takersList}>
                    {partTakers.map(tk => (
                      <span key={tk.id} className={`${styles.takerTag} ${tk.done ? styles.takerDone : ''}`}>
                        {tk.done ? '✓ ' : ''}{tk.name}{tk.is_me ? ' (أنت)' : ''}
                      </span>
                    ))}
                  </div>
                )}
              </div>

              <div className={styles.partActions}>
                {partTakers.length > 0 && (
                  <span className={styles.takerCount} title={partTakers.map(tk=>tk.name).join('، ')}>
                    👥 {partTakers.length}
                  </span>
                )}

                {(myName || iClaimed) && (
                  <button
                    className={`${styles.claimBtn} ${iClaimed ? styles.claimBtnMine : ''}`}
                    onClick={() => handleClaim(part)}
                    disabled={claiming === pi}>
                    {claiming === pi ? '...' : iClaimed ? (iDone ? '✓ خلّصت' : '📖 أنا') : '+ أنا هاخده'}
                  </button>
                )}
                {iClaimed && !iDone && claiming !== pi && (
                  <button className={styles.changeName} onClick={() => handleRelease(part)} title="ترك الجزء">
                    ✕
                  </button>
                )}
              </div>

              {part.done && part.done_at && (
                <span className={styles.doneDate}>
                  {part.done_by_name ? `${part.done_by_name} · ` : ''}{new Date(part.done_at).toLocaleDateString('ar-EG')}
                </span>
              )}
            </div>
          );
        })}
      </div>

      {/* Room actions */}
      <div className={styles.createBtns} style={{ margin: '20px 0 32px' }}>
        {isOwner ? (
          <>
            {!isComplete && (
              <button className={styles.backStepBtn} style={{ flex: 1 }} onClick={() => setConfirm('round')}>🔄 ختمة جديدة</button>
            )}
            <button className={styles.backStepBtn} style={{ flex: 1, color: '#f87171' }} onClick={() => setConfirm('delete')}>🗑️ حذف الخاتمة</button>
          </>
        ) : (
          <button className={styles.backStepBtn} style={{ flex: 1 }} onClick={() => setConfirm('leave')}>🚪 الخروج من الخاتمة</button>
        )}
      </div>

      {/* Confirm modal (in-app) */}
      {confirm && (
        <div className={styles.modal} onClick={e => { if (e.target === e.currentTarget && !busy) setConfirm(null); }}>
          <div className={styles.modalBox}>
            <h3>{CONFIRMS[confirm].title}</h3>
            <p>{CONFIRMS[confirm].body}</p>
            <div className={styles.modalBtns}>
              <button className={styles.nextBtn} style={{ flex: 1 }} onClick={runConfirmed} disabled={busy}>
                {busy ? '...' : CONFIRMS[confirm].ok}
              </button>
              <button className={styles.backStepBtn} onClick={() => setConfirm(null)} disabled={busy}>إلغاء</button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
