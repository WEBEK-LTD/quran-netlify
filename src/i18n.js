export function detectLang() {
  const saved = localStorage.getItem('nq_ui_lang');
  if (saved && TRANSLATIONS[saved]) return saved;
  const b = (navigator.language || 'ar').split('-')[0].toLowerCase();
  if (TRANSLATIONS[b]) return b;
  if (b === 'ms') return 'id';
  if (['az','kk','uz','tk'].includes(b)) return 'tr';
  return 'ar';
}

export function getLang() { return detectLang(); }

export function setLang(code) {
  localStorage.setItem('nq_ui_lang', code);
  window.dispatchEvent(new CustomEvent('nq-lang-change', { detail: code }));
}

// ─── Hook ─────────────────────────────────────────────────────────────────────
export function useLang() {
  const [lang, setLangState] = useState(detectLang);
  useEffect(() => {
    const handler = (e) => setLangState(e.detail);
    window.addEventListener('nq-lang-change', handler);
    return () => window.removeEventListener('nq-lang-change', handler);
  }, []);
  return lang;
}

export function useT() {
  const lang = useLang();
  return (key, fallback) => {
    const val = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS['ar']?.[key] ?? fallback ?? key;
    return val;
  };
}

export function useDir() {
  const lang = useLang();
  return LANGS.find(l => l.code === lang)?.dir || 'rtl';
}

