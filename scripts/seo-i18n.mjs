// Meaning of a surah's name, or '' when it would only repeat the name
// (Hud, Luqman, Muhammad, Quraysh…), so titles never read "Surah Hud (Hud)".
const norm = x => String(x).toLowerCase().normalize('NFD').replace(/[^a-z]/g, '').replace(/^(al|an|ar|as|at|ad|adh|ash|az)(?=[a-z]{3})/, '');
export function meaningOf(s, lang) {
  const m = s.meaning[lang] || '';
  const name = lang === 'tr' ? s.tr : s.tl;
  if (lang === 'ur') return m;                     // Urdu meanings are never a bare repeat
  return m && norm(m) !== norm(name) ? m : '';
}
const par = (s, lang) => (meaningOf(s, lang) ? ` (${meaningOf(s, lang)})` : '');

